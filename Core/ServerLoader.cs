using System.Collections.Generic;
using System.Diagnostics;
using System.Linq;
using UnityEngine;

namespace QuanChunkLoader.Core
{
    /// <summary>
    /// Runs on the server only. Keeps forced zones loaded and their objects instantiated, and applies the ownership
    /// rule (docs/design.md, "How loading and ownership work"):
    /// - the server claims a forced-zone object only while no connected player's vanilla area covers it;
    /// - vanilla's own 2 s pass (ZDOMan.ReleaseNearbyZDOS) then hands it to a player who comes near;
    /// - a claim by a player far away is taken back on the next pass.
    /// Players' range checks are never patched, so clients load and own exactly what vanilla gives them.
    /// </summary>
    internal sealed class ServerLoader : MonoBehaviour
    {
        private const float ZoneInterval = 0.1f;
        private const float CreateInterval = 0.1f;
        private const int CreatePerTick = 20;
        private const float OwnershipInterval = 2f;
        private const float SummaryInterval = 300f;
        private const int LargeChange = 20;

        /// <summary>True while this machine is the server and the loader has started for the current world.</summary>
        internal static bool Running { get; private set; }

        private float _zoneTimer;
        private float _createTimer;
        private float _ownershipTimer;
        private float _summaryTimer;
        private float _secondTimer;

        private readonly List<ZDO> _zoneObjects = new List<ZDO>();
        private readonly HashSet<ZDOID> _unknownLogged = new HashSet<ZDOID>();

        private struct Seen
        {
            internal long Owner;
            internal string Category;
        }

        private Dictionary<ZDOID, Seen> _lastPass = new Dictionary<ZDOID, Seen>();
        private Dictionary<ZDOID, Seen> _thisPass = new Dictionary<ZDOID, Seen>();
        private int _lastPassForcedVersion = -1;

        private struct PlayerArea
        {
            internal long Uid;
            internal Vector3 RefPos;
        }

        private readonly List<PlayerArea> _players = new List<PlayerArea>();

        private static bool ServerReady =>
            ZNet.instance != null && ZNet.instance.IsServer() && ZDOMan.instance != null &&
            ZNetScene.instance != null && ZoneSystem.instance != null &&
            ZNet.GetConnectionStatus() == ZNet.ConnectionStatus.Connected;

        private void Update()
        {
            if (!ServerReady)
            {
                if (Running)
                {
                    Stop();
                }
                return;
            }
            if (!Running)
            {
                Start_();
            }

            var dt = Time.unscaledDeltaTime;
            if ((_secondTimer += dt) >= 1f)
            {
                _secondTimer = 0f;
                Observers.ServerTick();
            }
            if (Observers.Forced.Count == 0 && _lastPass.Count == 0)
            {
                return;
            }
            if ((_zoneTimer += dt) >= ZoneInterval)
            {
                _zoneTimer = 0f;
                KeepZonesLoaded();
            }
            if ((_createTimer += dt) >= CreateInterval)
            {
                _createTimer = 0f;
                CreateObjects();
            }
            if ((_ownershipTimer += dt) >= OwnershipInterval)
            {
                _ownershipTimer = 0f;
                var summary = (_summaryTimer += OwnershipInterval) >= SummaryInterval;
                if (summary)
                {
                    _summaryTimer = 0f;
                }
                OwnershipPass(summary);
            }
        }

        private void Start_()
        {
            Running = true;
            _lastPass.Clear();
            _unknownLogged.Clear();
            _summaryTimer = SummaryInterval - 30f; // first summary half a minute after start
            Observers.ServerStart();
        }

        private void Stop()
        {
            Running = false;
            _lastPass.Clear();
            Observers.ServerStop();
        }

        private void OnDestroy()
        {
            Running = false;
        }

        // ---- Zones ---------------------------------------------------------------------------------------

        /// <summary>
        /// Pokes every forced zone so it stays loaded, loading at most one new zone per tick as vanilla does.
        /// Zones not yet generated are generated by the game as for a visiting player.
        /// </summary>
        private static void KeepZonesLoaded()
        {
            var loadedOne = false;
            foreach (var zone in Observers.Forced)
            {
                if (ZoneSystem.instance.IsZoneLoaded(zone))
                {
                    GameAccess.PokeLocalZone(zone); // resets its time to live
                }
                else if (!loadedOne && GameAccess.PokeLocalZone(zone))
                {
                    loadedOne = true;
                    Log.Debug($"Zone {zone.x},{zone.y} loaded.");
                }
            }
        }

        // ---- Objects -------------------------------------------------------------------------------------

        private void FindZoneObjects(Vector2s zone)
        {
            _zoneObjects.Clear();
            ZDOMan.instance.FindSectorObjects(zone, new SimulationDistance(0, 0), _zoneObjects);
        }

        /// <summary>
        /// Instantiates forced-zone objects the server hasn't created yet, a few per tick. Tames, wild creatures
        /// and unknown prefabs are skipped (see ObjectKinds.ServerLoads); the scene patch keeps what's created.
        /// </summary>
        private void CreateObjects()
        {
            var budget = CreatePerTick;
            foreach (var zone in Observers.Forced)
            {
                if (!ZoneSystem.instance.IsZoneLoaded(zone))
                {
                    continue;
                }
                FindZoneObjects(zone);
                foreach (var zdo in _zoneObjects)
                {
                    if (zdo.Created)
                    {
                        continue;
                    }
                    if (!ObjectKinds.ServerLoads(zdo))
                    {
                        if (ObjectKinds.Of(zdo) == Kind.UnknownPrefab && _unknownLogged.Add(zdo.m_uid))
                        {
                            var p = zdo.GetPosition();
                            Log.Warning($"Unknown prefab (hash {zdo.GetPrefab()}) at ({p.x:0}, {p.z:0}) zone {zone.x},{zone.y}: " +
                                        "left alone, not loaded. Is a mod missing on the server?");
                        }
                        continue;
                    }
                    if (!ZoneSystem.instance.IsZoneReadyForType(zone, zdo.Type))
                    {
                        continue;
                    }
                    var go = GameAccess.CreateObject(zdo);
                    if (go == null)
                    {
                        continue; // never destroyed: the safety rule for unknown objects
                    }
                    if (Log.DebugOn)
                    {
                        Log.Debug($"Loaded {Utils.GetPrefabName(go)} {zdo.m_uid} in zone {zone.x},{zone.y}.");
                    }
                    if (--budget <= 0)
                    {
                        return;
                    }
                }
            }
        }

        // ---- Ownership -------------------------------------------------------------------------------------

        private void CollectPlayerAreas()
        {
            _players.Clear();
            foreach (var peer in ZNet.instance.GetPeers())
            {
                if (peer.IsReady())
                {
                    _players.Add(new PlayerArea { Uid = peer.m_uid, RefPos = peer.GetRefPos() });
                }
            }
            // In a local game the host is a player too.
            if (!ZNet.instance.IsDedicated() && Player.m_localPlayer != null)
            {
                _players.Add(new PlayerArea { Uid = ZDOMan.GetSessionID(), RefPos = ZNet.instance.GetReferencePosition() });
            }
        }

        // Vanilla's own test, unpatched: ZNetScene.InActiveArea.
        private bool Covers(long uid, Vector3 pos)
        {
            foreach (var p in _players)
            {
                if (p.Uid == uid)
                {
                    return ZNetScene.InActiveArea(pos, p.RefPos);
                }
            }
            return false;
        }

        private bool AnyPlayerCovers(Vector3 pos)
        {
            foreach (var p in _players)
            {
                if (ZNetScene.InActiveArea(pos, p.RefPos))
                {
                    return true;
                }
            }
            return false;
        }

        private sealed class Tally
        {
            private readonly Dictionary<string, int> _counts = new Dictionary<string, int>();
            internal int Total;

            internal void Add(string key)
            {
                _counts.TryGetValue(key, out var n);
                _counts[key] = n + 1;
                Total++;
            }

            public override string ToString() =>
                string.Join(", ", _counts.OrderByDescending(kv => kv.Value).Select(kv => $"{kv.Value} {kv.Key}"));
        }

        private void OwnershipPass(bool summary)
        {
            var watch = Stopwatch.StartNew();
            var session = ZDOMan.GetSessionID();
            CollectPlayerAreas();

            var claimed = 0;
            var leftBehind = new Tally();      // players who moved away: normal
            var distantClaims = new Tally();   // a far player took an object: taken back
            var distantCategories = new Tally();
            var released = new Tally();        // tames or creatures held by a far player: released to nobody

            var owners = summary ? new Tally() : null;
            int objects = 0, instantiated = 0, tamesPaused = 0, wildPaused = 0;

            _thisPass.Clear();
            foreach (var zone in Observers.Forced)
            {
                FindZoneObjects(zone);
                foreach (var zdo in _zoneObjects)
                {
                    if (!zdo.Persistent)
                    {
                        continue;
                    }
                    var kind = ObjectKinds.Of(zdo);
                    if (kind == Kind.Player)
                    {
                        continue;
                    }
                    var pos = zdo.GetPosition();
                    var owner = zdo.GetOwner();
                    var id = zdo.m_uid;
                    _lastPass.TryGetValue(id, out var before);
                    var hadBefore = _lastPass.ContainsKey(id);

                    if (owner == session)
                    {
                        // Vanilla hands it to a player who comes near.
                    }
                    else if (owner == 0)
                    {
                        if (ObjectKinds.ServerClaims(zdo) && !AnyPlayerCovers(pos))
                        {
                            zdo.SetOwner(session);
                            owner = session;
                            claimed++;
                            Log.Trace($"Claimed unowned {ObjectKinds.Category(zdo)} {id}.");
                        }
                    }
                    else if (!Covers(owner, pos) && !AnyPlayerCovers(pos))
                    {
                        // Owned by a player who isn't near it (or isn't connected), and nobody else is near.
                        var who = Observers.PlayerName(owner);
                        if (ObjectKinds.ServerClaims(zdo))
                        {
                            var category = ObjectKinds.Category(zdo);
                            if (hadBefore && before.Owner == owner)
                            {
                                leftBehind.Add(who);
                            }
                            else
                            {
                                distantClaims.Add(who);
                                distantCategories.Add(category);
                            }
                            zdo.SetOwner(session);
                            owner = session;
                            Log.Debug($"Took {category} {id} at ({pos.x:0}, {pos.z:0}) from {who}, who isn't near it.");
                        }
                        else if (kind == Kind.Creature && zdo.GetInt(ZDOVars.s_inUse) == 0)
                        {
                            // A paused tame or wild creature held by someone far away: released, as vanilla does
                            // when a player walks away, so no distant client keeps it. The server doesn't take it.
                            zdo.SetOwner(0L);
                            owner = 0;
                            released.Add(who);
                            Log.Debug($"Released {ObjectKinds.Category(zdo)} {id} from {who}, who isn't near it.");
                        }
                    }

                    _thisPass[id] = new Seen { Owner = owner, Category = hadBefore ? before.Category : ObjectKinds.Category(zdo) };

                    if (summary)
                    {
                        objects++;
                        owners.Add(Observers.PlayerName(owner));
                        if (ZNetScene.instance.FindInstance(zdo) != null)
                        {
                            instantiated++;
                        }
                        else if (kind == Kind.Creature)
                        {
                            if (ObjectKinds.IsTame(zdo)) tamesPaused++;
                            else wildPaused++;
                        }
                    }
                }
            }

            ReportMovedOut();

            if (distantClaims.Total > 0)
            {
                var line = $"Took back {distantClaims.Total} object(s) claimed by players far from them ({distantClaims}): " +
                           $"{distantCategories}. A client-side mod may be claiming objects at a distance.";
                if (distantClaims.Total >= LargeChange) Log.Warning(line);
                else Log.Info(line);
            }
            if (leftBehind.Total > 0)
            {
                Log.Debug($"Took over {leftBehind.Total} object(s) players moved away from ({leftBehind}).");
            }
            if (released.Total > 0)
            {
                Log.Debug($"Released {released.Total} paused creature(s) held by players far away ({released}).");
            }
            if (claimed > 0)
            {
                Log.Debug($"Claimed {claimed} unowned object(s) in loaded zones.");
            }

            var swap = _lastPass;
            _lastPass = _thisPass;
            _thisPass = swap;
            _lastPassForcedVersion = Observers.ForcedVersion;

            watch.Stop();
            Log.Trace($"Ownership pass: {_lastPass.Count} objects in {Observers.Forced.Count} zones, {watch.Elapsed.TotalMilliseconds:0.0} ms.");

            if (summary && Observers.Forced.Count > 0)
            {
                var active = Observers.All.Values.Count(o => o.On);
                Log.Info($"Summary: {Observers.Forced.Count} zone(s) loaded by {active} observer(s); {objects} objects, " +
                         $"owners: {owners}; {instantiated} running on the server; " +
                         $"{tamesPaused} tame(s) and {wildPaused} wild creature(s) paused.");
            }
        }

        /// <summary>
        /// Objects seen in forced zones last pass that are now outside them while the set itself didn't change:
        /// they moved. Many at once is what the 1 Nov 2026 tame incident looked like, so it's a warning.
        /// </summary>
        private void ReportMovedOut()
        {
            if (_lastPassForcedVersion != Observers.ForcedVersion)
            {
                return; // zones were dropped or added: objects "leaving" is expected
            }
            var categories = new Tally();
            var owners = new Tally();
            foreach (var kv in _lastPass)
            {
                if (_thisPass.ContainsKey(kv.Key))
                {
                    continue;
                }
                var zdo = ZDOMan.instance.GetZDO(kv.Key);
                if (zdo == null || Observers.IsForced(zdo.GetSector()))
                {
                    continue; // destroyed (picked up, eaten, killed) or no longer persistent
                }
                categories.Add(kv.Value.Category);
                owners.Add(Observers.PlayerName(zdo.GetOwner()));
                if (Log.DebugOn)
                {
                    var p = zdo.GetPosition();
                    Log.Debug($"{kv.Value.Category} {kv.Key} left the loaded zones, now at ({p.x:0}, {p.z:0}), owner {Observers.PlayerName(zdo.GetOwner())}.");
                }
            }
            if (categories.Total >= LargeChange)
            {
                Log.Warning($"{categories.Total} objects left the loaded zones within one pass ({categories}); " +
                            $"owned now by: {owners}.");
            }
            else if (categories.Total > 0)
            {
                Log.Debug($"{categories.Total} object(s) left the loaded zones ({categories}).");
            }
        }
    }
}
